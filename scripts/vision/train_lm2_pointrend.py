def resolve_initial_weights(
    custom_weights_path: Optional[Union[str, Path]],
    project_root: Path,
    logger: logging.Logger,
) -> Tuple[str, str]:
    """
    Resolves the initial checkpoint weights for LeafMachine2 PCD fine-tuning.
    Checks candidate locations in priority order:
      1. User-supplied CLI argument (--weights)
      2. models/LeafPriority.pth or models/checkpoints/LeafPriority.pth
      3. LeafMachine2 embedded PCD weights (PLANT_LeafPriority / Group3)
      4. Detectron2 PointRend COCO model zoo baseline URL
    """
    candidates: List[Tuple[str, Path]] = []

    if custom_weights_path:
        p = Path(custom_weights_path)
        candidates.append(("User-Specified Path", p if p.is_absolute() else project_root / p))

    # Standard model cache locations
    candidates.extend([
        ("Project Models Directory (pth)", project_root / "models" / "LeafPriority.pth"),
        ("Project Models Checkpoints (pth)", project_root / "models" / "checkpoints" / "LeafPriority.pth"),
        ("Project Models Directory (pt)", project_root / "models" / "LeafPriority.pt"),
        (
            "LeafMachine2 Native Group3 PCD Segmentation Model (model_final.pth)",
            project_root
            / "LeafMachine2"
            / "leafmachine2"
            / "segmentation"
            / "models"
            / "Group3_Dataset_100000_Iter_1176PTS_512Batch_smooth_l1_LR00025_BGR"
            / "model_final.pth",
        ),
        (
            "LeafMachine2 Native GroupB PCD Segmentation Model (model_final.pth)",
            project_root
            / "LeafMachine2"
            / "leafmachine2"
            / "segmentation"
            / "models"
            / "GroupB_Dataset_100000_Iter_1176PTS_512Batch_smooth_l1_LR00025_BGR"
            / "model_final.pth",
        ),
        (
            "LeafMachine2 Component Detector Weights (LeafPriority.pt)",
            project_root
            / "LeafMachine2"
            / "leafmachine2"
            / "component_detector"
            / "runs"
            / "train"
            / "Plant_Detector"
            / "PLANT_LeafPriority"
            / "PLANT_LeafPriority"
            / "weights"
            / "LeafPriority.pt",
        ),
    ])

    for source_desc, cand_path in candidates:
        if cand_path.exists() and cand_path.is_file() and cand_path.stat().st_size > 1024:
            logger.info(f"Found initial PCD weights [{source_desc}]: {cand_path.resolve()}")
            return str(cand_path.resolve()), source_desc

    # Fallback to Detectron2 PointRend standard COCO checkpoint URL
    zoo_url = "detectron2://PointRend/InstanceSegmentation/pointrend_rcnn_R_50_FPN_3x_coco/164955410/model_final_edd263.pkl"
    logger.warning(
        f"No local LeafPriority weights found on disk. Falling back to Detectron2 PointRend baseline: {zoo_url}"
    )
    return zoo_url, "Detectron2 Model Zoo PointRend Baseline"


