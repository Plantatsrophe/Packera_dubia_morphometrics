def build_pointrend_config(args: argparse.Namespace, logger: logging.Logger) -> CfgNode:
    """
    Construct and validate the Detectron2 CfgNode for PointRend instance segmentation
    with backbone layer freezing, class configuration, and fine-tuning learning rate.
    """
    cfg = get_cfg()
    point_rend.add_pointrend_config(cfg)

    # Locate base PointRend R-50 FPN config file inside LeafMachine2
    lm2_detectron = PROJECT_ROOT / "LeafMachine2" / "leafmachine2" / "segmentation" / "detectron2"
    base_pointrend_yaml = (
        lm2_detectron
        / "projects"
        / "PointRend"
        / "configs"
        / "InstanceSegmentation"
        / "pointrend_rcnn_R_50_FPN_3x_coco.yaml"
    )

    if base_pointrend_yaml.exists():
        cfg.merge_from_file(str(base_pointrend_yaml.resolve()))
        logger.info(f"Merged base PointRend config from: {base_pointrend_yaml.name}")
    else:
        # Programmatic configuration fallback
        logger.info("Configuring PointRend architecture programmatically...")
        cfg.MODEL.META_ARCHITECTURE = "GeneralizedRCNN"
        cfg.MODEL.BACKBONE.NAME = "build_resnet_fpn_backbone"
        cfg.MODEL.RESNETS.OUT_FEATURES = ["res2", "res3", "res4", "res5"]
        cfg.MODEL.FPN.IN_FEATURES = ["res2", "res3", "res4", "res5"]
        cfg.MODEL.ANCHOR_GENERATOR.SIZES = [[32], [64], [128], [256], [512]]
        cfg.MODEL.ANCHOR_GENERATOR.ASPECT_RATIOS = [[0.5, 1.0, 2.0]]
        cfg.MODEL.RPN.IN_FEATURES = ["p2", "p3", "p4", "p5", "p6"]
        cfg.MODEL.RPN.PRE_NMS_TOPK_TRAIN = 2000
        cfg.MODEL.RPN.PRE_NMS_TOPK_TEST = 1000
        cfg.MODEL.RPN.POST_NMS_TOPK_TRAIN = 1000
        cfg.MODEL.RPN.POST_NMS_TOPK_TEST = 1000
        cfg.MODEL.ROI_HEADS.NAME = "StandardROIHeads"
        cfg.MODEL.ROI_HEADS.IN_FEATURES = ["p2", "p3", "p4", "p5"]
        cfg.MODEL.ROI_BOX_HEAD.NAME = "FastRCNNConvFCHead"
        cfg.MODEL.ROI_BOX_HEAD.NUM_FC = 2
        cfg.MODEL.ROI_BOX_HEAD.POOLER_RESOLUTION = 7
        cfg.MODEL.ROI_BOX_HEAD.TRAIN_ON_PRED_BOXES = True
        cfg.MODEL.MASK_ON = True
        cfg.MODEL.ROI_MASK_HEAD.NAME = "PointRendMaskHead"
        cfg.MODEL.ROI_MASK_HEAD.NUM_CONV = 4
        cfg.MODEL.ROI_MASK_HEAD.NUM_FC = 2
        cfg.MODEL.ROI_MASK_HEAD.FC_DIM = 1024
        cfg.MODEL.ROI_MASK_HEAD.OUTPUT_SIDE_RESOLUTION = 7
        cfg.MODEL.ROI_MASK_HEAD.IN_FEATURES = ["p2"]
        cfg.MODEL.ROI_MASK_HEAD.POINT_HEAD_ON = True
        cfg.MODEL.ROI_MASK_HEAD.POOLER_TYPE = ""
        cfg.MODEL.POINT_HEAD.NAME = "StandardPointHead"
        cfg.MODEL.POINT_HEAD.IN_FEATURES = ["p2"]
        cfg.MODEL.POINT_HEAD.FC_DIM = 256
        cfg.MODEL.POINT_HEAD.NUM_FC = 3

    # Dataset bindings
    cfg.DATASETS.TRAIN = (args.train_dataset_name,)
    if args.val_dataset_name:
        cfg.DATASETS.TEST = (args.val_dataset_name,)
    else:
        cfg.DATASETS.TEST = ()

    # Target class configuration (ideal_leaf, partial_leaf)
    cfg.MODEL.ROI_HEADS.NUM_CLASSES = NUM_CLASSES
    cfg.MODEL.POINT_HEAD.NUM_CLASSES = NUM_CLASSES
    cfg.INPUT.MASK_FORMAT = "bitmask"

    # Anti-Catastrophic Forgetting: Backbone Freezing
    # FREEZE_AT = 2 freezes Stem (conv1/bn1) and res2 stage
    # FREEZE_AT = 3 freezes Stem + res2 + res3
    cfg.MODEL.BACKBONE.FREEZE_AT = int(args.freeze_at)

    # Initial weights initialization
    weights_path, _ = resolve_initial_weights(args.weights, PROJECT_ROOT, logger)
    cfg.MODEL.WEIGHTS = weights_path

    # Solver & Optimizer Hyperparameters
    cfg.SOLVER.BASE_LR = float(args.lr)
    cfg.SOLVER.MAX_ITER = int(args.iterations)
    cfg.SOLVER.IMS_PER_BATCH = int(args.batch_size)
    cfg.DATALOADER.NUM_WORKERS = int(args.num_workers)

    # Multi-step learning rate decay schedule (default: decay at 60% and 80% of MAX_ITER)
    step1 = int(round(cfg.SOLVER.MAX_ITER * 0.60))
    step2 = int(round(cfg.SOLVER.MAX_ITER * 0.80))
    cfg.SOLVER.STEPS = (step1, step2)
    cfg.SOLVER.GAMMA = 0.1
    cfg.SOLVER.WARMUP_FACTOR = 0.001
    cfg.SOLVER.WARMUP_ITERS = min(100, int(cfg.SOLVER.MAX_ITER * 0.05))
    cfg.SOLVER.WARMUP_METHOD = "linear"
    cfg.SOLVER.CHECKPOINT_PERIOD = int(args.checkpoint_period)

    # Evaluation frequency
    cfg.TEST.EVAL_PERIOD = int(args.eval_period) if args.val_dataset_name else 0

    # Device configuration
    if args.cpu or not torch.cuda.is_available():
        cfg.MODEL.DEVICE = "cpu"
    else:
        cfg.MODEL.DEVICE = "cuda"

    # Destination directory for logs, checkpoints, and weights
    cfg.OUTPUT_DIR = str(Path(args.output_dir).resolve())
    os.makedirs(cfg.OUTPUT_DIR, exist_ok=True)

    return cfg


