def register_pcd_coco_dataset(
    dataset_name: str,
    coco_json_path: Path,
    images_dir: Path,
    logger: logging.Logger,
) -> bool:
    """
    Safely registers a COCO 1.0 JSON dataset into Detectron2's DatasetCatalog
    and configures MetadataCatalog with target class names and colors.
    """
    if not coco_json_path.exists():
        logger.error(f"COCO JSON dataset file not found: {coco_json_path.resolve()}")
        return False

    if not images_dir.exists():
        logger.warning(f"Images directory not found at {images_dir.resolve()}. Checking fallback search paths...")
        # Fallback to data/raw_vouchers if LM2 symlinks not yet generated
        fallback_raw = PROJECT_ROOT / "data" / "raw_vouchers"
        if fallback_raw.exists():
            images_dir = fallback_raw
            logger.info(f"Using fallback images directory: {images_dir.resolve()}")
        else:
            logger.error(f"Could not locate image directory: {images_dir.resolve()}")
            return False

    # Check if already registered (clean re-registration)
    if dataset_name in DatasetCatalog.list():
        logger.debug(f"Dataset '{dataset_name}' already registered in catalog. Using existing entry.")
        return True

    register_coco_instances(
        name=dataset_name,
        metadata={},
        json_file=str(coco_json_path.resolve()),
        image_root=str(images_dir.resolve()),
    )

    # Set metadata for visualizers and evaluation
    MetadataCatalog.get(dataset_name).set(
        thing_classes=TARGET_CLASSES,
        thing_colors=CLASS_COLORS,
        json_file=str(coco_json_path.resolve()),
        image_root=str(images_dir.resolve()),
        evaluator_type="coco",
    )

    try:
        dataset_dicts = DatasetCatalog.get(dataset_name)
        total_annotations = sum(len(d.get("annotations", [])) for d in dataset_dicts)
        logger.info(
            f"Successfully registered dataset '{dataset_name}': "
            f"{len(dataset_dicts)} images, {total_annotations} annotations."
        )
        return True
    except Exception as e:
        logger.error(f"Failed to load registered dataset '{dataset_name}': {e}")
        return False


