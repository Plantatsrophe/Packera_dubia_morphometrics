def setup_environment_paths() -> Path:
    """
    Ensure LeafMachine2 and bundled Detectron2 / PointRend packages are on sys.path.
    If required dependencies (e.g. fvcore, iopath) are missing in the current Python
    environment, automatically re-execute with the dedicated .venv_LM2 interpreter.
    """
    script_path = Path(__file__).resolve()
    # Search upwards for repo root
    project_root = script_path.parents[2] if len(script_path.parents) >= 3 else script_path.parent
    for parent in [script_path.parent] + list(script_path.parents):
        if (parent / "LeafMachine2").exists() or (parent / ".git").exists() or (parent / "LM2_Project").exists():
            project_root = parent
            break

    # 1. Check if dedicated LeafMachine2 virtual environment exists and is needed
    lm2_prefix = project_root / ".venv_LM2"
    lm2_python = lm2_prefix / "bin" / "python"
    if not lm2_python.exists():
        lm2_python = lm2_prefix / "bin" / "python3"

    try:
        import fvcore
        import iopath
    except ImportError:
        # If running from another venv (e.g., .venv) and .venv_LM2 is available, auto re-exec
        if lm2_python.exists() and lm2_prefix.exists():
            if Path(sys.prefix).resolve() != lm2_prefix.resolve() and os.environ.get("LM2_AUTO_REEXEC") != "1":
                env = dict(os.environ)
                env["LM2_AUTO_REEXEC"] = "1"
                env["VIRTUAL_ENV"] = str(lm2_prefix)
                env["PATH"] = str(lm2_prefix / "bin") + ":" + env.get("PATH", "")
                os.execve(str(lm2_python), [str(lm2_python)] + sys.argv, env)

    lm2_root = project_root / "LeafMachine2"
    lm2_pkg = lm2_root / "leafmachine2"
    lm2_detectron = lm2_pkg / "segmentation" / "detectron2"

    paths_to_add = [
        str(project_root),
        str(lm2_root),
        str(lm2_pkg),
        str(lm2_detectron),
    ]

    for p in paths_to_add:
        if os.path.exists(p) and p not in sys.path:
            sys.path.insert(0, p)

    return project_root


