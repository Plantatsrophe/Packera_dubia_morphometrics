# ===============================================================================
# MAIN PIPELINE ENTRYPOINT
# ===============================================================================

def main() -> int:
    """Orchestrates LeafMachine2 PCD PointRend fine-tuning pipeline."""
    args = parse_arguments()
    logger = setup_logging(output_dir=args.output_dir, verbose=args.verbose)

    logger.info("=================================================================")
    logger.info(" LeafMachine2 PCD PointRend Fine-Tuning Pipeline (Packera dubia)")
    logger.info("=================================================================")
    logger.info(f" Execution Timestamp   : {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    logger.info(f" PyTorch Version       : {torch.__version__} (CUDA Available: {torch.cuda.is_available()})")
    logger.info(f" Detectron2 Version    : {detectron2.__version__}")
    if torch.cuda.is_available() and not args.cpu:
        logger.info(f" Active GPU Device     : {torch.cuda.get_device_name(0)}")
    logger.info(f" Training COCO JSON    : {args.coco_json.resolve()}")
    logger.info(f" Voucher Images Root   : {args.images_dir.resolve()}")
    logger.info(f" Target Output Dir     : {args.output_dir.resolve()}")
    logger.info(f" Target Weights Name   : {args.output_name}")
    logger.info(f" Base Learning Rate    : {args.lr}")
    logger.info(f" Total Iterations      : {args.iterations}")
    logger.info(f" Backbone Freeze Level : FREEZE_AT = {args.freeze_at}")
    logger.info(f" Target PCD Classes    : {TARGET_CLASSES} (Category IDs: 1, 2)")
    logger.info("=================================================================\n")

    # 1. Register Training Dataset
    train_success = register_pcd_coco_dataset(
        dataset_name=args.train_dataset_name,
        coco_json_path=args.coco_json,
        images_dir=args.images_dir,
        logger=logger,
    )
    if not train_success:
        logger.error("Failed to register training COCO dataset. Aborting fine-tuning.")
        return 1

    # 2. Register Validation Dataset (if provided)
    if args.val_coco_json and args.val_coco_json.exists():
        register_pcd_coco_dataset(
            dataset_name=args.val_dataset_name,
            coco_json_path=args.val_coco_json,
            images_dir=args.images_dir,
            logger=logger,
        )
    else:
        args.val_dataset_name = None

    # 3. Build PointRend Configuration
    cfg = build_pointrend_config(args, logger)

    # 4. Instantiate Model & Audit Layer Freezing
    model = build_model(cfg)
    audit_stats = audit_and_verify_model_layers(model, cfg.MODEL.BACKBONE.FREEZE_AT, logger)

    if args.dry_run:
        logger.info("\n[DRY RUN] Configuration and model layer audit completed successfully.")
        logger.info(f"[DRY RUN] Weights to load on run: {cfg.MODEL.WEIGHTS}")
        logger.info(f"[DRY RUN] Output weights destination: {(args.output_dir / args.output_name).resolve()}")
        logger.info("Exiting without executing training loop as requested (--dry-run).")
        return 0

    # 5. Evaluation Only Mode
    if args.eval_only:
        if not args.val_dataset_name:
            logger.error("Evaluation mode requires a valid validation dataset (--val-coco-json).")
            return 1
        logger.info("Running evaluation on validation dataset...")
        DetectionCheckpointer(model, save_dir=cfg.OUTPUT_DIR).resume_or_load(
            cfg.MODEL.WEIGHTS, resume=args.resume
        )
        evaluator = PCDPointRendTrainer.build_evaluator(cfg, args.val_dataset_name)
        val_loader = build_detection_test_loader(cfg, args.val_dataset_name)
        results = inference_on_dataset(model, val_loader, evaluator)
        logger.info(f"Evaluation Results:\n{json.dumps(results, indent=2)}")
        return 0

    # 6. Initialize Trainer & Execute Fine-Tuning Loop
    logger.info("\nInitializing PCDPointRendTrainer and loading initial weights...")
    trainer = PCDPointRendTrainer(cfg)
    trainer.resume_or_load(resume=args.resume)

    start_time = time.time()
    logger.info(f"Beginning fine-tuning for exactly {cfg.SOLVER.MAX_ITER} iterations...")

    try:
        trainer.train()
    except Exception as e:
        logger.error(f"Error during training execution: {e}", exc_info=True)
        return 1

    elapsed_time = time.time() - start_time
    logger.info(f"Training completed in {elapsed_time/60.0:.2f} minutes ({elapsed_time:.1f} seconds).")

    # 7. Post-Training Artifacts & Weight Export
    target_weights, cfg_yaml, metadata = export_lm2_artifacts(
        cfg=cfg,
        output_dir=args.output_dir,
        weights_name=args.output_name,
        logger=logger,
    )

    logger.info("=================================================================")
    logger.info("       LEAFMACHINE2 PCD POINTREND FINE-TUNING SUMMARY            ")
    logger.info("=================================================================")
    logger.info(f" Final Model Weights Exported : {target_weights.resolve()}")
    logger.info(f" Detectron2 Config Exported   : {cfg_yaml.resolve()}")
    logger.info(f" Detector Metadata Exported   : {metadata.resolve()}")
    logger.info(f" Total Training Iterations    : {cfg.SOLVER.MAX_ITER}")
    logger.info(f" Target Supervised Categories : {TARGET_CLASSES}")
    logger.info(f" Status                       : READY FOR LEAFMACHINE2 INFERENCE")
    logger.info("=================================================================\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
