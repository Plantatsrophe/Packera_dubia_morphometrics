def export_lm2_artifacts(
    cfg: CfgNode,
    output_dir: Path,
    weights_name: str,
    logger: logging.Logger,
) -> Tuple[Path, Path, Path]:
    """
    Exports the final fine-tuned model checkpoint as `Packera_LeafPriority.pth`
    along with `cfg_output.yaml` and `metadata.json` for direct use in LeafMachine2.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    # 1. Output weights file (Packera_LeafPriority.pth)
    model_final_path = output_dir / "model_final.pth"
    target_weights_path = output_dir / weights_name

    if model_final_path.exists():
        shutil.copyfile(model_final_path, target_weights_path)
        logger.info(f"Exported primary PCD weights to: {target_weights_path.resolve()}")
    else:
        # Check for checkpoint models
        ckpts = sorted(list(output_dir.glob("model_*.pth")))
        if ckpts:
            latest_ckpt = ckpts[-1]
            shutil.copyfile(latest_ckpt, target_weights_path)
            logger.info(f"Exported checkpoint [{latest_ckpt.name}] as: {target_weights_path.resolve()}")
        else:
            logger.warning(f"No checkpoint file found in {output_dir.resolve()} to rename to {weights_name}.")

    # Also copy to project models/ directory if accessible
    models_dir = PROJECT_ROOT / "models"
    if models_dir.exists() and target_weights_path.exists():
        dest_model = models_dir / weights_name
        try:
            shutil.copyfile(target_weights_path, dest_model)
            logger.info(f"Mirrored production weights to: {dest_model.resolve()}")
        except Exception as e:
            logger.debug(f"Could not mirror weights to models/: {e}")

    # 2. Export cfg_output.yaml
    cfg_output_path = output_dir / "cfg_output.yaml"
    with open(cfg_output_path, "w", encoding="utf-8") as f:
        f.write(cfg.dump())
    logger.info(f"Exported Detectron2 config to: {cfg_output_path.resolve()}")

    # 3. Export metadata.json
    metadata_path = output_dir / "metadata.json"
    metadata_content = {
        "thing_classes": TARGET_CLASSES,
        "thing_colors": CLASS_COLORS,
        "num_classes": NUM_CLASSES,
        "dataset_name": cfg.DATASETS.TRAIN[0] if cfg.DATASETS.TRAIN else "pcd_packera_train",
        "date_trained": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "base_model": "PointRend_R_50_FPN",
        "weights_file": weights_name,
        "iterations": cfg.SOLVER.MAX_ITER,
        "base_lr": cfg.SOLVER.BASE_LR,
        "taxonomic_scope": "Packera dubia complex (basal rosette blade & petiole segmentation)",
    }
    with open(metadata_path, "w", encoding="utf-8") as f:
        json.dump(metadata_content, f, indent=2)
    logger.info(f"Exported LM2 detector metadata to: {metadata_path.resolve()}")

    return target_weights_path, cfg_output_path, metadata_path


