def audit_and_verify_model_layers(model: nn.Module, freeze_at: int, logger: logging.Logger) -> Dict[str, Any]:
    """
    Audits model parameters, verifying which layers are frozen vs trainable.
    Logs parameter statistics and ensures early ResNet stages have requires_grad=False.
    """
    total_params = 0
    trainable_params = 0
    frozen_params = 0

    frozen_layer_groups: List[str] = []
    trainable_layer_groups: List[str] = []

    for name, param in model.named_parameters():
        num_el = param.numel()
        total_params += num_el
        if param.requires_grad:
            trainable_params += num_el
            # Summarize group names
            grp = ".".join(name.split(".")[:2])
            if grp not in trainable_layer_groups:
                trainable_layer_groups.append(grp)
        else:
            frozen_params += num_el
            grp = ".".join(name.split(".")[:2])
            if grp not in frozen_layer_groups:
                frozen_layer_groups.append(grp)

    trainable_pct = (trainable_params / total_params * 100.0) if total_params > 0 else 0.0
    frozen_pct = (frozen_params / total_params * 100.0) if total_params > 0 else 0.0

    logger.info("=================================================================")
    logger.info("          MODEL PARAMETER & LAYER FREEZING AUDIT                 ")
    logger.info("=================================================================")
    logger.info(f" Backbone FREEZE_AT Level : {freeze_at} (0=None, 1=Stem, 2=Stem+Res2, 3=Stem+Res2+Res3)")
    logger.info(f" Total Parameters         : {total_params:,}")
    logger.info(f" Trainable Parameters     : {trainable_params:,} ({trainable_pct:.2f}%)")
    logger.info(f" Frozen Parameters        : {frozen_params:,} ({frozen_pct:.2f}%)")
    logger.info(f" Frozen Layer Groups      : {', '.join(frozen_layer_groups) if frozen_layer_groups else '(None)'}")
    logger.info(f" Trainable Layer Groups   : {', '.join(trainable_layer_groups)}")
    logger.info("=================================================================")

    return {
        "total_params": total_params,
        "trainable_params": trainable_params,
        "frozen_params": frozen_params,
        "trainable_pct": trainable_pct,
        "frozen_pct": frozen_pct,
        "freeze_at": freeze_at,
    }


